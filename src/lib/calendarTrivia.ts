// ＝＝＝ 日本の祝日判定 ＝＝＝
export function getJapaneseHoliday(year: number, month: number, day: number): string | null {
  // 固定祝日
  if (month === 1 && day === 1) return "元日";
  if (month === 2 && day === 11) return "建国記念の日";
  if (month === 2 && day === 23) return "天皇誕生日";
  if (month === 4 && day === 29) return "昭和の日";
  if (month === 5 && day === 3) return "憲法記念日";
  if (month === 5 && day === 4) return "みどりの日";
  if (month === 5 && day === 5) return "こどもの日";
  if (month === 8 && day === 11) return "山の日";
  if (month === 11 && day === 3) return "文化の日";
  if (month === 11 && day === 23) return "勤労感謝の日";

  // ハッピーマンデー（成人の日: 1月第2月曜、海の日: 7月第3月曜、敬老の日: 9月第3月曜、スポーツの日: 10月第2月曜）
  const dayOfWeek = new Date(year, month - 1, day).getDay(); // 0:日, 1:月...
  const nthMonday = Math.floor((day - 1) / 7) + 1;

  if (dayOfWeek === 1) {
    if (month === 1 && nthMonday === 2) return "成人の日";
    if (month === 7 && nthMonday === 3) return "海の日";
    if (month === 9 && nthMonday === 3) return "敬老の日";
    if (month === 10 && nthMonday === 2) return "スポーツの日";
  }

  // 春分の日（3月20日頃）・秋分の日（9月22〜23日頃）の簡易天文計算
  if (month === 3) {
    const vernalEquinox = Math.floor(20.8431 + 0.242194 * (year - 1980) - Math.floor((year - 1980) / 4));
    if (day === vernalEquinox) return "春分の日";
  }
  if (month === 9) {
    const autumnEquinox = Math.floor(23.2488 + 0.242194 * (year - 1980) - Math.floor((year - 1980) / 4));
    if (day === autumnEquinox) return "秋分の日";
    // シルバーウィークの「国民の休日」（敬老の日と秋分の日に挟まれた火曜日）
    if (dayOfWeek === 2 && nthMonday === 3 && day === autumnEquinox - 1) {
      return "国民の休日";
    }
  }

  // 振替休日判定（前日が日曜日かつ祝日だった場合）
  if (day > 1 && dayOfWeek === 1) {
    const prevHoliday = getJapaneseHoliday(year, month, day - 1);
    if (prevHoliday && prevHoliday !== "振替休日") {
      return "振替休日";
    }
  }

  return null;
}

